import type {
  SidebarEntry,
  SidebarGroup,
  SidebarLink,
  StarlightRouteData,
} from '@astrojs/starlight/utils/routing/types';
import type { StarlightSidebarLabelSortOptions } from './types.ts';

export function cleanPath(href: string): string {
  return href
    .replace(/^[a-zA-Z]+:\/\/[^/]+/, '')
    .replace(/^\//, '')
    .replace(/\/$/, '')
    .replace(/\.(mdx?|html)$/, '');
}

export function getEntryOrder(
  entry: SidebarEntry,
  docOrderMap: Map<string, number>
): number | undefined {
  if (entry.type === 'link') {
    const cleaned = cleanPath(entry.href);
    return (
      docOrderMap.get(cleaned) ??
      docOrderMap.get('/' + cleaned) ??
      docOrderMap.get(entry.href)
    );
  }
  return undefined;
}

export function isExternalLink(item: SidebarEntry): boolean {
  if (item.type !== 'link') return false;
  return /^[a-zA-Z][a-zA-Z\d+\-.]*:/.test(item.href);
}

export function getPinnedRank(item: SidebarEntry, patterns: (string | RegExp)[] = []): number {
  if (patterns.length === 0) return -1;
  const label = (item.label || '').trim().toLowerCase();
  const href = (item.type === 'link' ? item.href : '').toLowerCase();
  const slug = href.split('/').filter(Boolean).pop() || '';

  for (let i = 0; i < patterns.length; i++) {
    const p = patterns[i];
    if (typeof p === 'string') {
      const pattern = p.trim().toLowerCase();
      if (label === pattern) return i;
      if (
        slug === pattern ||
        href.endsWith('/' + pattern) ||
        href.endsWith('/' + pattern + '/')
      ) {
        return i;
      }
    } else if (p instanceof RegExp) {
      if (p.test(label) || p.test(href) || p.test(slug)) {
        return i;
      }
    }
  }
  return -1;
}

export function isAutogeneratedEntry(item: SidebarEntry): boolean {
  return 'autogenerate' in item;
}

export function shouldSortGroup(
  group: SidebarGroup,
  onlyAutogenerated = true
): boolean {
  if (!onlyAutogenerated) return true;
  if (isAutogeneratedEntry(group)) return true;
  return group.entries.some((entry) => isAutogeneratedEntry(entry));
}

export function compareEntries(
  a: SidebarEntry,
  b: SidebarEntry,
  collator: Intl.Collator,
  docOrderMap: Map<string, number>,
  options: {
    pinned?: (string | RegExp)[];
    pinnedBottom?: (string | RegExp)[];
    externalLinksAtBottom?: boolean;
    respectOrder?: boolean;
  } = {}
): number {
  const {
    pinned = ['visao-geral', 'visão geral', 'overview', 'index', 'introducao', 'introdução'],
    pinnedBottom = [],
    externalLinksAtBottom = true,
    respectOrder = true,
  } = options;

  // 1. Pinned items at top
  const aPinned = getPinnedRank(a, pinned);
  const bPinned = getPinnedRank(b, pinned);
  if (aPinned !== -1 && bPinned !== -1) {
    if (aPinned !== bPinned) return aPinned - bPinned;
  } else if (aPinned !== -1) {
    return -1;
  } else if (bPinned !== -1) {
    return 1;
  }

  // 2. Pinned items at bottom
  const aPinnedBottom = getPinnedRank(a, pinnedBottom);
  const bPinnedBottom = getPinnedRank(b, pinnedBottom);
  if (aPinnedBottom !== -1 && bPinnedBottom !== -1) {
    if (aPinnedBottom !== bPinnedBottom) return aPinnedBottom - bPinnedBottom;
  } else if (aPinnedBottom !== -1) {
    return 1;
  } else if (bPinnedBottom !== -1) {
    return -1;
  }

  // 3. External links at the bottom
  if (externalLinksAtBottom) {
    const aExt = isExternalLink(a);
    const bExt = isExternalLink(b);
    if (aExt && !bExt) return 1;
    if (!aExt && bExt) return -1;
  }

  // 4. Respect explicit frontmatter order if present
  if (respectOrder && docOrderMap.size > 0) {
    const aOrder = getEntryOrder(a, docOrderMap);
    const bOrder = getEntryOrder(b, docOrderMap);
    if (aOrder !== undefined && bOrder !== undefined) {
      if (aOrder !== bOrder) return aOrder - bOrder;
    } else if (aOrder !== undefined) {
      return -1;
    } else if (bOrder !== undefined) {
      return 1;
    }
  }

  // 5. Sort alphabetically by label
  const labelA = a.label || '';
  const labelB = b.label || '';
  const result = collator.compare(labelA, labelB);
  if (result !== 0) return result;

  // Fallback: compare href/slug
  const hrefA = a.type === 'link' ? a.href : '';
  const hrefB = b.type === 'link' ? b.href : '';
  return hrefA.localeCompare(hrefB);
}

export function sortEntries(
  entries: SidebarEntry[],
  collator: Intl.Collator,
  docOrderMap: Map<string, number>,
  options: StarlightSidebarLabelSortOptions = {}
): SidebarEntry[] {
  const onlyAutogenerated = options.onlyAutogenerated ?? true;

  return entries.map((entry) => {
    if (entry.type === 'group') {
      const sortedChildren = sortEntries(entry.entries, collator, docOrderMap, options);
      if (shouldSortGroup(entry, onlyAutogenerated)) {
        return {
          ...entry,
          entries: [...sortedChildren].sort((a, b) =>
            compareEntries(a, b, collator, docOrderMap, options)
          ),
        };
      }
      return {
        ...entry,
        entries: sortedChildren,
      };
    }
    return entry;
  });
}

export function flattenSidebar(sidebar: SidebarEntry[]): SidebarLink[] {
  return sidebar.flatMap((entry) =>
    entry.type === 'group' ? flattenSidebar(entry.entries) : entry
  );
}

export function applyPaginationOverride(
  link: SidebarLink | undefined,
  override: unknown
): SidebarLink | undefined {
  if (override === false) return undefined;
  if (override === true) return link;
  if (typeof override === 'string' && link) {
    return { ...link, label: override };
  }
  if (typeof override === 'object' && override !== null) {
    const custom = override as { label?: string; link?: string };
    if (link) {
      return {
        ...link,
        label: custom.label ?? link.label,
        href: custom.link ?? link.href,
        attrs: {},
      };
    }
    if (custom.link && custom.label) {
      return {
        type: 'link',
        label: custom.label,
        href: custom.link,
        isCurrent: false,
        badge: undefined,
        attrs: {},
      };
    }
  }
  return link;
}

export function updatePagination(
  starlightRoute: StarlightRouteData,
  syncPagination = true
): void {
  if (!syncPagination) return;
  if (!starlightRoute.pagination) return;
  if (starlightRoute.entry?.data?.pagination === false) return;

  const flatLinks = flattenSidebar(starlightRoute.sidebar);
  const currentIndex = flatLinks.findIndex((item) => item.isCurrent);
  if (currentIndex === -1) return;

  const prevLink = flatLinks[currentIndex - 1];
  const nextLink = flatLinks[currentIndex + 1];

  starlightRoute.pagination = {
    prev: applyPaginationOverride(prevLink, starlightRoute.entry?.data?.prev),
    next: applyPaginationOverride(nextLink, starlightRoute.entry?.data?.next),
  };
}
