import type { SidebarEntry } from '@astrojs/starlight/utils/routing/types';

export interface StarlightSidebarLabelSortOptions {
  /**
   * Locale used by `Intl.Collator` for alphabetical sorting.
   * If omitted, falls back to the current route language or `'pt-BR'`.
   * @default 'pt-BR'
   */
  locale?: string | string[];

  /**
   * Options passed to `Intl.Collator`.
   * @default { sensitivity: 'base', numeric: true }
   */
  collatorOptions?: Intl.CollatorOptions;

  /**
   * List of string patterns, regex patterns, or predicate functions for items that should be pinned to the top of their group.
   * By default, overview pages like 'visao-geral', 'overview', 'index', 'introducao' are pinned.
   * @default ['visao-geral', 'visão geral', 'overview', 'index', 'introducao', 'introdução']
   */
  pinned?: (string | RegExp)[];

  /**
   * List of string patterns or regex patterns for items that should be pinned to the bottom of their group.
   * @default []
   */
  pinnedBottom?: (string | RegExp)[];

  /**
   * If `true`, only sort groups where entries were generated by Starlight's `autogenerate` feature.
   * Manually specified sidebar order in `astro.config.mjs` is preserved.
   * @default true
   */
  onlyAutogenerated?: boolean;

  /**
   * Whether to place external links (e.g. `https://...`) at the bottom of the group.
   * @default true
   */
  externalLinksAtBottom?: boolean;

  /**
   * Whether to update `starlightRoute.pagination` (previous/next page links)
   * so they match the newly sorted sidebar order.
   * @default true
   */
  syncPagination?: boolean;

  /**
   * Whether to respect `sidebar.order` in page frontmatter if present.
   * Lower numbers appear first. Items with equal or no order are sorted alphabetically by label.
   * @default true
   */
  respectOrder?: boolean;
}
