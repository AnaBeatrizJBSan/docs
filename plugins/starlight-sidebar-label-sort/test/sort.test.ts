import test from 'node:test';
import assert from 'node:assert/strict';
import type { SidebarEntry, SidebarGroup, SidebarLink } from '@astrojs/starlight/utils/routing/types';
import { sortEntries, updatePagination, flattenSidebar } from '../utils.ts';

const collator = new Intl.Collator('pt-BR', { sensitivity: 'base', numeric: true });

function makeLink(label: string, href: string, autogenerated = true): SidebarLink {
  return {
    type: 'link',
    label,
    href,
    isCurrent: false,
    badge: undefined,
    attrs: {},
    ...(autogenerated ? { autogenerate: { directory: 'test' } } : {}),
  } as SidebarLink;
}

function makeGroup(label: string, entries: SidebarEntry[], autogenerated = false): SidebarGroup {
  return {
    type: 'group',
    label,
    entries,
    collapsed: false,
    badge: undefined,
    ...(autogenerated ? { autogenerate: { directory: 'test' } } : {}),
  } as SidebarGroup;
}

test('sorts autogenerated items alphabetically by label', () => {
  const entries: SidebarEntry[] = [
    makeGroup('Ativadores', [
      makeLink('Habbo anda no Mobi', '/ativadores/wf_trg_walks_on_furni/'),
      makeLink('Batida', '/ativadores/wf_trg_collision/'),
      makeLink('Começo de Jogo', '/ativadores/wf_trg_game_starts/'),
      makeLink('Bot alcança usuário', '/ativadores/wf_trg_bot_reached_avtr/'),
    ]),
  ];

  const sorted = sortEntries(entries, collator, new Map());
  const group = sorted[0] as SidebarGroup;
  const labels = group.entries.map((e) => e.label);

  assert.deepEqual(labels, [
    'Batida',
    'Bot alcança usuário',
    'Começo de Jogo',
    'Habbo anda no Mobi',
  ]);
});

test('pins Visão Geral / overview to the top of the group', () => {
  const entries: SidebarEntry[] = [
    makeGroup('Ativadores', [
      makeLink('Habbo anda no Mobi', '/ativadores/wf_trg_walks_on_furni/'),
      makeLink('Batida', '/ativadores/wf_trg_collision/'),
      makeLink('Visão Geral', '/ativadores/visao-geral/'),
      makeLink('Começo de Jogo', '/ativadores/wf_trg_game_starts/'),
    ]),
  ];

  const sorted = sortEntries(entries, collator, new Map());
  const group = sorted[0] as SidebarGroup;
  const labels = group.entries.map((e) => e.label);

  assert.equal(labels[0], 'Visão Geral');
  assert.deepEqual(labels.slice(1), [
    'Batida',
    'Começo de Jogo',
    'Habbo anda no Mobi',
  ]);
});

test('respects explicit frontmatter order over alphabetical sorting', () => {
  const orderMap = new Map<string, number>();
  orderMap.set('guias/primeiro-sistema', 0);
  orderMap.set('guias/segundo-passo', 1);

  const entries: SidebarEntry[] = [
    makeGroup('Guias', [
      makeLink('Zebra (sem order)', '/guias/zebra/'),
      makeLink('Segundo Passo (order: 1)', '/guias/segundo-passo/'),
      makeLink('Primeiro Sistema (order: 0)', '/guias/primeiro-sistema/'),
      makeLink('Abelha (sem order)', '/guias/abelha/'),
    ]),
  ];

  const sorted = sortEntries(entries, collator, orderMap, { respectOrder: true });
  const group = sorted[0] as SidebarGroup;
  const labels = group.entries.map((e) => e.label);

  assert.deepEqual(labels, [
    'Primeiro Sistema (order: 0)',
    'Segundo Passo (order: 1)',
    'Abelha (sem order)',
    'Zebra (sem order)',
  ]);
});

test('keeps external links at the bottom of the group', () => {
  const entries: SidebarEntry[] = [
    makeGroup('Guias', [
      makeLink('Mais Tutoriais', 'https://example.com/tutoriais', false),
      makeLink('Tutorial B', '/guias/tutorial-b/'),
      makeLink('Tutorial A', '/guias/tutorial-a/'),
    ]),
  ];

  const sorted = sortEntries(entries, collator, new Map(), { externalLinksAtBottom: true });
  const group = sorted[0] as SidebarGroup;
  const labels = group.entries.map((e) => e.label);

  assert.deepEqual(labels, [
    'Tutorial A',
    'Tutorial B',
    'Mais Tutoriais',
  ]);
});

test('preserves manual groups when onlyAutogenerated is true', () => {
  const manualGroup = makeGroup('Referência', [
    makeLink('Glossário', '/referencia/glossario/', false),
    makeLink('Tipos de Wired', '/referencia/tipos-de-wireds/', false),
    makeLink('Configurando Wireds', '/referencia/configurando-wireds/', false),
    makeLink('Arquivo Wired', '/referencia/arquivo-wired/', false),
  ], false);

  const sorted = sortEntries([manualGroup], collator, new Map(), { onlyAutogenerated: true });
  const group = sorted[0] as SidebarGroup;
  const labels = group.entries.map((e) => e.label);

  // Manual ordering preserved
  assert.deepEqual(labels, [
    'Glossário',
    'Tipos de Wired',
    'Configurando Wireds',
    'Arquivo Wired',
  ]);
});

test('recalculates pagination based on the new sorted sidebar', () => {
  const linkVisaoGeral = makeLink('Visão Geral', '/ativadores/visao-geral/');
  const linkBatida = { ...makeLink('Batida', '/ativadores/batida/'), isCurrent: true };
  const linkHabbo = makeLink('Habbo anda no Mobi', '/ativadores/habbo/');

  const routeData: any = {
    sidebar: [
      makeGroup('Ativadores', [
        linkVisaoGeral,
        linkBatida,
        linkHabbo,
      ]),
    ],
    pagination: {
      prev: undefined,
      next: undefined,
    },
    entry: {
      data: {},
    },
  };

  updatePagination(routeData, true);

  assert.equal(routeData.pagination.prev?.label, 'Visão Geral');
  assert.equal(routeData.pagination.next?.label, 'Habbo anda no Mobi');
});
