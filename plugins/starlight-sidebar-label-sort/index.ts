import type { StarlightPlugin } from '@astrojs/starlight/types';
import { fileURLToPath } from 'node:url';
import type { StarlightSidebarLabelSortOptions } from './types.ts';

export type { StarlightSidebarLabelSortOptions } from './types.ts';

export default function starlightSidebarLabelSort(
  options: StarlightSidebarLabelSortOptions = {}
): StarlightPlugin {
  const pluginConfig = {
    locale: options.locale ?? 'pt-BR',
    collatorOptions: options.collatorOptions ?? { sensitivity: 'base', numeric: true },
    pinned: (options.pinned ?? ['visao-geral', 'visão geral', 'overview', 'index', 'introducao', 'introdução']).map(
      (p) => (p instanceof RegExp ? p.source : p)
    ),
    pinnedBottom: (options.pinnedBottom ?? []).map((p) => (p instanceof RegExp ? p.source : p)),
    onlyAutogenerated: options.onlyAutogenerated ?? true,
    externalLinksAtBottom: options.externalLinksAtBottom ?? true,
    syncPagination: options.syncPagination ?? true,
    respectOrder: options.respectOrder ?? true,
  };

  const virtualModuleId = 'virtual:starlight-sidebar-label-sort/config';
  const resolvedVirtualModuleId = '\0' + virtualModuleId;

  return {
    name: 'starlight-sidebar-label-sort',
    hooks: {
      'config:setup'({ addIntegration, addRouteMiddleware }) {
        addIntegration({
          name: 'starlight-sidebar-label-sort-integration',
          hooks: {
            'astro:config:setup'({ updateConfig }) {
              updateConfig({
                vite: {
                  plugins: [
                    {
                      name: 'vite-plugin-starlight-sidebar-label-sort-config',
                      resolveId(id) {
                        if (id === virtualModuleId) {
                          return resolvedVirtualModuleId;
                        }
                      },
                      load(id) {
                        if (id === resolvedVirtualModuleId) {
                          return `export const config = ${JSON.stringify(pluginConfig)}; export default config;`;
                        }
                      },
                    },
                  ],
                },
              });
            },
          },
        });

        addRouteMiddleware({
          entrypoint: fileURLToPath(new URL('./middleware.ts', import.meta.url)),
        });
      },
    },
  };
}
