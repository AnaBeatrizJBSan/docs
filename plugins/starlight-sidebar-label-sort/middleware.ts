import { defineRouteMiddleware } from '@astrojs/starlight/route-data';
import type {
  SidebarEntry,
  SidebarGroup,
  SidebarLink,
  StarlightRouteData,
} from '@astrojs/starlight/utils/routing/types';
import config from 'virtual:starlight-sidebar-label-sort/config';

let docOrderCache: Map<string, number> | null = null;

async function getDocOrderMap(): Promise<Map<string, number>> {
  if (docOrderCache) return docOrderCache;
  const map = new Map<string, number>();

  if (config.respectOrder) {
    try {
      const { getCollection } = await import('astro:content');
      const docs = await getCollection('docs');
      for (const doc of docs) {
        const order = doc.data?.sidebar?.order;
        if (typeof order === 'number') {
          const cleanId = doc.id.replace(/\.(mdx?|markdown)$/i, '');
          map.set(cleanId, order);
          map.set('/' + cleanId, order);
          map.set('/' + cleanId + '/', order);
          if (doc.slug) {
            map.set(doc.slug, order);
            map.set('/' + doc.slug, order);
            map.set('/' + doc.slug + '/', order);
          }
        }
      }
    } catch {
      // Safely fall back if collection cannot be queried
    }
  }

  docOrderCache = map;
  return map;
}

function cleanPath(href: string): string {
  return href
    .replace(/^[a-zA-Z]+:\/\/[^/]+/, '')
    .replace(/^\//, '')
    .replace(/\/$/, '')
    .replace(/\.(mdx?|html)$/, '');
}

function getEntryOrder(entry: SidebarEntry, docOrderMap: Map<string, number>): number | undefined {
  if (entry.type === 'link') {
    const cleaned = cleanPath(entry.href);
    return (
      docOrderMap.get(cleaned) ??
      docOrderMap.get('/' + cleaned) ??
      docOrderMap.get(entry.href)
    );
  }
  return undefined;
}

function isExternalLink(item: SidebarEntry): boolean {
  if (item.type !== 'link') return false;
  return /^[a-zA-Z][a-zA-Z\d+\-.]*:/.test(item.href);
}

function getPinnedRank(item: SidebarEntry, patterns: string[] = []): number {
  if (patterns.length === 0) return -1;
  const label = (item.label || '').trim().toLowerCase();
  const href = (item.type === 'link' ? item.href : '').toLowerCase();
  const slug = href.split('/').filter(Boolean).pop() || '';

  for (let i = 0; i < patterns.length; i++) {
    const pattern = patterns[i].trim().toLowerCase();
    if (label === pattern) return i;
    if (
      slug === pattern ||
      href.endsWith('/' + pattern) ||
      href.endsWith('/' + pattern + '/')
    ) {
      return i;
    }
  }
  return -1;
}

function isAutogeneratedEntry(item: SidebarEntry): boolean {
  return 'autogenerate' in item;
}

function shouldSortGroup(group: SidebarGroup): boolean {
  if (!config.onlyAutogenerated) return true;
  if (isAutogeneratedEntry(group)) return true;
  return group.entries.some((entry) => isAutogeneratedEntry(entry));
}

function compareEntries(
  a: SidebarEntry,
  b: SidebarEntry,
  collator: Intl.Collator,
  docOrderMap: Map<string, number>
): number {
  // 1. Pinned items at top (e.g. Visão Geral)
  const aPinned = getPinnedRank(a, config.pinned);
  const bPinned = getPinnedRank(b, config.pinned);
  if (aPinned !== -1 && bPinned !== -1) {
    if (aPinned !== bPinned) return aPinned - bPinned;
  } else if (aPinned !== -1) {
    return -1;
  } else if (bPinned !== -1) {
    return 1;
  }

  // 2. Pinned items at bottom
  const aPinnedBottom = getPinnedRank(a, config.pinnedBottom);
  const bPinnedBottom = getPinnedRank(b, config.pinnedBottom);
  if (aPinnedBottom !== -1 && bPinnedBottom !== -1) {
    if (aPinnedBottom !== bPinnedBottom) return aPinnedBottom - bPinnedBottom;
  } else if (aPinnedBottom !== -1) {
    return 1;
  } else if (bPinnedBottom !== -1) {
    return -1;
  }

  // 3. External links at the bottom
  if (config.externalLinksAtBottom) {
    const aExt = isExternalLink(a);
    const bExt = isExternalLink(b);
    if (aExt && !bExt) return 1;
    if (!aExt && bExt) return -1;
  }

  // 4. Respect explicit frontmatter order if present
  if (config.respectOrder && docOrderMap.size > 0) {
    const aOrder = getEntryOrder(a, docOrderMap);
    const bOrder = getEntryOrder(b, docOrderMap);
    if (aOrder !== undefined && bOrder !== undefined) {
      if (aOrder !== bOrder) return aOrder - bOrder;
    } else if (aOrder !== undefined) {
      return -1;
    } else if (bOrder !== undefined) {
      return 1;
    }
  }

  // 5. Sort alphabetically by label
  const labelA = a.label || '';
  const labelB = b.label || '';
  const result = collator.compare(labelA, labelB);
  if (result !== 0) return result;

  // Fallback: compare href/slug
  const hrefA = a.type === 'link' ? a.href : '';
  const hrefB = b.type === 'link' ? b.href : '';
  return hrefA.localeCompare(hrefB);
}

function sortEntries(
  entries: SidebarEntry[],
  collator: Intl.Collator,
  docOrderMap: Map<string, number>
): SidebarEntry[] {
  return entries.map((entry) => {
    if (entry.type === 'group') {
      const sortedChildren = sortEntries(entry.entries, collator, docOrderMap);
      if (shouldSortGroup(entry)) {
        return {
          ...entry,
          entries: [...sortedChildren].sort((a, b) =>
            compareEntries(a, b, collator, docOrderMap)
          ),
        };
      }
      return {
        ...entry,
        entries: sortedChildren,
      };
    }
    return entry;
  });
}

function flattenSidebar(sidebar: SidebarEntry[]): SidebarLink[] {
  return sidebar.flatMap((entry) =>
    entry.type === 'group' ? flattenSidebar(entry.entries) : entry
  );
}

function applyPaginationOverride(
  link: SidebarLink | undefined,
  override: unknown
): SidebarLink | undefined {
  if (override === false) return undefined;
  if (override === true) return link;
  if (typeof override === 'string' && link) {
    return { ...link, label: override };
  }
  if (typeof override === 'object' && override !== null) {
    const custom = override as { label?: string; link?: string };
    if (link) {
      return {
        ...link,
        label: custom.label ?? link.label,
        href: custom.link ?? link.href,
        attrs: {},
      };
    }
    if (custom.link && custom.label) {
      return {
        type: 'link',
        label: custom.label,
        href: custom.link,
        isCurrent: false,
        badge: undefined,
        attrs: {},
      };
    }
  }
  return link;
}

function updatePagination(starlightRoute: StarlightRouteData) {
  if (!config.syncPagination) return;
  if (!starlightRoute.pagination) return;
  if (starlightRoute.entry?.data?.pagination === false) return;

  const flatLinks = flattenSidebar(starlightRoute.sidebar);
  const currentIndex = flatLinks.findIndex((item) => item.isCurrent);
  if (currentIndex === -1) return;

  const prevLink = flatLinks[currentIndex - 1];
  const nextLink = flatLinks[currentIndex + 1];

  starlightRoute.pagination = {
    prev: applyPaginationOverride(prevLink, starlightRoute.entry?.data?.prev),
    next: applyPaginationOverride(nextLink, starlightRoute.entry?.data?.next),
  };
}

export const onRequest = defineRouteMiddleware(async (context) => {
  const { starlightRoute } = context.locals;
  if (!starlightRoute?.sidebar) return;

  const locale = config.locale || starlightRoute.lang || 'pt-BR';
  const collator = new Intl.Collator(locale, config.collatorOptions);
  const docOrderMap = await getDocOrderMap();

  starlightRoute.sidebar = sortEntries(starlightRoute.sidebar, collator, docOrderMap);

  updatePagination(starlightRoute);
});
